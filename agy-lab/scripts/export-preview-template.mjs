// Exports the free-preview page template (src/v21/step3.ts: reportPage) to the public site, as plain JavaScript.
//   node scripts/export-preview-template.mjs [target-folder]      default target: G:\mirrormirror\server\preview-template
// Run it again whenever the template changes; it overwrites the files in the target and nothing else.
// What it writes:  page.js (reportPage, missingPage), rules.js (the few rules the page uses), two rule JSON files,
//                  samples/*.jpg (the sample report pictures the page embeds).
// A tool for a developer, not part of the pipeline: it does not touch any report or database.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const target = path.resolve(process.argv[2] ?? 'G:/mirrormirror/server/preview-template');
const lines = (file) => readFileSync(path.join(src, file), 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/);

// A slice of a source file by line numbers (1-based, inclusive). The first line must start with `anchor`, so a moved
// template stops this script loudly instead of exporting the wrong lines.
function slice(all, from, to, anchor, name) {
  if (!all[from - 1]?.startsWith(anchor)) throw new Error(`${name}: line ${from} no longer starts with "${anchor}". The source moved; update this script.`);
  return all.slice(from - 1, to).join('\n');
}
const strip = (code) => stripTypeScriptTypes(code, { mode: 'strip' });

// ---- the page: step3.ts from "the page" to the end of the file, plus the sample-picture reader
const s3 = lines('v21/step3.ts');
const pageStart = s3.findIndex((l) => l.startsWith('// ---------------------------------------------------------------- the page')) + 1;
if (!pageStart) throw new Error('step3.ts: the "the page" marker is gone. Update this script.');
const pic = slice(s3, 31, 42, '/** A sample report page', 'sample pictures');
const page = [
  `// Generated by company-diver agy-lab/scripts/export-preview-template.mjs from src/v21/step3.ts. Do not edit here:`,
  `// change the template in company-diver and export again.`,
  `import { readFileSync } from 'node:fs';`,
  `import { daysToImpact, localeFor, plural, rankKey, severity } from './rules.js';`,
  strip(pic.replace('./samples/${name}', './samples/${name}').replace('[v21 step3]', '[preview template]')),
  strip(s3.slice(pageStart - 1).join('\n')),
].join('\n\n');

// ---- the rules the page uses: report-rules/index.ts, only those functions (it also holds phone-number code we do not need)
const rr = lines('report-rules/index.ts');
const rules = [
  `// Generated by company-diver agy-lab/scripts/export-preview-template.mjs from src/report-rules/index.ts. Do not edit here.`,
  `import { readFileSync } from 'node:fs';`,
  strip(slice(rr, 5, 19, 'const currencies', 'locale').replace(/^export type Locale.*$/m, '')),
  strip(slice(rr, 46, 46, 'export function plural', 'plural')),
  strip(slice(rr, 64, 77, 'const datePattern', 'dates')),
  strip(slice(rr, 112, 127, 'export type Urgency', 'severity')),
].join('\n');

mkdirSync(path.join(target, 'samples'), { recursive: true });
writeFileSync(path.join(target, 'page.js'), page + '\n');
writeFileSync(path.join(target, 'rules.js'), rules + '\n');
for (const f of ['country-currencies.json', 'month-first-countries.json']) copyFileSync(path.join(src, 'report-rules', f), path.join(target, f));
for (const f of readdirSync(path.join(src, 'v21/samples'))) copyFileSync(path.join(src, 'v21/samples', f), path.join(target, 'samples', f));
console.log(`exported the preview template to ${target}`);
